console.log("\n٥) ورقة ٢ · توزيع أعمار المراجعين");
{
  const cls=[[8,14,20],[15,21,15],[22,28,10],[29,35,10],[36,42,5]];
  const N=cls.reduce((a,b)=>a+b[2],0);
  ok(N===60,"مجموع التكرارات 60");
  const width=cls[1][0]-cls[0][0];
  check("sw2_f1",width,"سعة الفئة");
  const c4=cls[3];
  check("sw2_f2",`${c4[0]-0.5} → ${c4[1]+0.5}`,"الحدود الفعلية للفئة الرابعة");
  // دون 21.5 = الحدّ الفعلي الأعلى للفئة الثانية ⟵ التجمّع الصاعد عنده
  let cum=0;const pts=[[cls[0][0]-0.5,0]];
  cls.forEach(c=>{cum+=c[2];pts.push([c[1]+0.5,cum])});
  const under=pts.find(p=>p[0]===21.5);
  check("sw2_f3",under[1],"العدد دون 21.5 عاماً");
  const least=cls.reduce((a,b)=>b[2]<a[2]?b:a);
  check("sw2_f4",(least[0]+least[1])/2,"مركز الفئة الأقلّ تكراراً");
  // بين 14.5 و35.5 ⟵ الفئات الثانية والثالثة والرابعة
  const mid=cls.filter(c=>c[0]-0.5>=14.5&&c[1]+0.5<=35.5).reduce((a,b)=>a+b[2],0);
  ok(mid===35,"التكرار داخل المدى 35");
  check("sw2_f5",R(mid/N*100)+"%","التكرار المئوي بين 14.5 و35.5");
  check("sw2_f6",`(${pts[1][0]} , ${pts[1][1]})`,"النقطة الثانية في المضلّع المتجمّع");
  ok(JSON.stringify(pts)==="[[7.5,0],[14.5,20],[21.5,35],[28.5,45],[35.5,55],[42.5,60]]",
     "ونقاط المضلّع كلّها "+JSON.stringify(pts));
}

