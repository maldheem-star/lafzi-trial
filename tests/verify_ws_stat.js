// تحقّقٌ مستقلّ من كل جوابٍ رقمي في عناصر ورقتَي العمل — أحص ١٠٢، ٥ سبتمبر.
//
// القاعدة في هذا المشروع: «الحسابات المعقّدة ⇒ سكربت node مستقلّ للتحقّق، لا حسابٌ
// ذهني». وهذا السكربت لا يقرأ الجواب من البنك ثم يُصدّقه، بل **يشتقّه من المعطيات
// أوّلاً** ثم يقابله بما في البنك — فلو نسخت خطأً من الورقة المرفوعة لظهر هنا.
// وقد ظهر فعلاً: مفتاح الورقة أشّر على 6 فئاتٍ لتسعين قيمة، والقاعدتان المنشورتان
// تعطيان 7 — فشُحن 7 صواباً و6 مموّهاً بآليةٍ مسمّاة.
//
//   node tests/verify_ws_stat.js
const fs=require("fs");
let fails=0;
const ok=(c,m)=>{console.log((c?"  ✓ ":"  ✗ FAIL ")+m);if(!c)fails++};
const R=(x,d=2)=>Math.round(x*10**d)/10**d;

// ── البنك يُقرأ من الملفّ نفسه لا يُعاد كتابته هنا ──
const src=fs.readFileSync(__dirname+"/../index.html","utf8");
function itemOf(id){
  const i=src.indexOf('{id:"'+id+'"');
  if(i<0)return null;
  // نهاية العنصر: أوّل `"},\n  {id:` أو نهاية البنك
  const j=src.indexOf('\n  {id:',i+5), k=src.indexOf('\n];',i+5);
  return src.slice(i,(j>0&&j<k)?j:k);
}
// الجواب الصحيح = نصّ الخيار الذي يحمل ok:true
function rightOf(id){
  const t=itemOf(id); if(!t)return null;
  const m=t.match(/\{t:"((?:[^"\\]|\\.)*)",ok:true/);
  return m?m[1]:null;
}
function check(id,expected,label){
  const got=rightOf(id);
  ok(got!==null,id+": العنصر موجود");
  if(got===null)return;
  ok(String(got)===String(expected),`${id} · ${label}: البنك «${got}» والمشتقّ «${expected}»`);
}

console.log("\n١) ورقة ٢ · السؤال الأول — قواعد الفئات والحدود");
{
  // ١) عدد الفئات لتسعين قيمة: أصغر k يحقّق 2^k ≥ n (وSturges توافقها)
  let k=1; while(Math.pow(2,k)<90)k++;
  const sturges=Math.round(1+3.322*Math.log10(90));
  ok(k===7&&sturges===7,`القاعدتان تعطيان 7 — 2^k≥n ⟵ ${k} · Sturges ⟵ ${R(1+3.322*Math.log10(90))}`);
  check("sw2_q1",k,"عدد الفئات");
  ok(Math.pow(2,6)===64&&64<90,"و6 لا تكفي (2⁶ = 64 < 90) — فهي المموّه المسمّى");

  check("sw2_q2",Math.ceil((63-8)/7),"سعة الفئة");            // 7.86 ⟵ 8
  // ٣) الفئة الأولى العملية 2−9 ⟵ السعة 8، والثانية 10−17، وحدّها الفعلي الأدنى 9.5
  const w3=(9-2)+1, low2=2+w3-0.5;
  ok(w3===8,"سعة الفئة من الحدود العملية 2−9 تساوي 8");
  check("sw2_q3",low2,"الحدّ الفعلي الأدنى للفئة الثانية");
  check("sw2_q4",8+(5-2)*5,"مركز الفئة الخامسة");
  // ٥) مركز الأولى 9 وسعتها 5 ⟵ الأولى 6.5→11.5، فالثانية 11.5→16.5
  const a1=9-5/2, b1=9+5/2;
  check("sw2_q5",`${b1} → ${b1+5}`,"الحدود الفعلية للفئة الثانية");
  ok(a1===6.5,"وحدود الفئة الأولى 6.5 → 11.5");
  check("sw2_q6",R(50/360*108),"عدد بيانات قطاعٍ زاويته 50°");
  check("sw2_q9",R((125-(15+20+25+10))/125,3),"التكرار النسبي للفئة الخامسة");
  check("sw2_q10",`(${(12+18)/2} , 8)`,"نقطة المضلّع التكراري");
}

