// ===== الاتّجاه يُقاس بالرسم لا بالنصّ — ٢٥ أغسطس =====
// أوّل لقطة شاشة بعد شحن قسم الإحصاء أظهرت سطراً **يُدرّس صيغةً خاطئة**: المصدر
// «الانحراف الربيعي = (Q₃ − Q₁) ÷ 2 = 2.5» يُعرض «... ÷ 2.5 = 2» — قسمةٌ على ٢٫٥
// لا على ٢. وثلاثةٌ مثله. والنصّ في DOM سليمٌ تماماً في الأربعة.
//
// **وكيف عُرفت الأربعة**: بُني كاشفٌ آليّ أوّلاً (مواضع الأعداد يجب أن تتزايد يساراً)
// فأبلغ عن **١١١** سطراً — ولقطةُ شاشةٍ لستٍّ منها أثبتت أن خمساً سليمة. فرُفض الكاشف
// ولم يُشحَن: **اختبارٌ نسبةُ بلاغه الكاذب هذه لا يحرس شيئاً، بل يُدرَّب الناس على تجاهله.**
// ثم ضُيّقت القاعدة إلى الشكل المؤكَّد (عربية + رمزٌ لاتيني + ذيلٌ رقميّ صرف)، وصُوِّرت
// أربع عشرة حالة، فتبيّن أن **أربعاً** منها فقط منقلبة فعلاً — وهي المثبَّتة أدناه.
//
// وجُرِّب عزلُ UAX #9 (U+2066/U+2069) علاجاً عامّاً فأفسد أسطراً كانت سليمة (١٣ − ٣ = ١٠
// صارت ١٠ = ٣ − ١٣) — فرُفض **بالقياس لا بالرأي**، وبقي العلاج المعتمَد في المشروع منذ
// ٢٥ أغسطس: المعادلة تُفصَل في سطرٍ بلا عربية فتُرسَم LTR.
//
// وهذا الاختبار حارسُ ارتداد: الصيغ الأربع المكسورة يجب ألّا تعود إلى الملفّ.
const fs=require('fs');
let fails=0;const ok=(c,m)=>{console.log((c?'  ✓ ':'  ✗ FAIL ')+m);if(!c)fails++};
const src=fs.readFileSync(__dirname+'/../index.html','utf8');

console.log('\n١) الصيغ الأربع المُثبَت انقلابُها بالصورة لا تعود');
const BROKEN=[
  ["الانحراف الربيعي = (Q₃ − Q₁) ÷ 2 = 2.5","يُعرض ÷ 2.5 = 2 — قسمةٌ على رقمٍ آخر"],
  ["الذيل الأيمن = أكبر قيمة − Q₃ = 13 − 12 = 1","يُعرض 1 = 12 − 13 = Q₃ معكوساً"],
  ["الذيل الأيسر = Q₁ − أصغر قيمة = 7 − 3 = 4","نفس الشكل"],
  ["الفضاء: عدد طرق اختيار ٣ من ١٥ = 15C3 = 455","يُعرض = 455 = 15C3 معكوساً"],
  // بعلامة إنهاء النصّ: الصيغة المُصلَحة تبدأ بالمكسورة نفسها («… × 4! = 17160»)،
  // فمطابقةٌ بلا مرساةٍ تُفشِل الاختبارَ على إصلاحه هو — وقع فعلاً في أوّل تشغيل.
  ['صحيح — 13P4 = 715 × 4!"','علامة التعجّب تنفصل إلى أوّل السطر فيصير 4 لا !4'],
];
BROKEN.forEach(function(p){
  ok(src.indexOf(p[0])<0,'لا تعود: «'+p[0].slice(0,44)+'» — '+p[1]);
});

console.log('\n٢) والبدائل المصوَّرة موجودةٌ فعلاً');
const FIXED=[
  "الانحراف الربيعي:\\n(Q₃ − Q₁) ÷ 2 = 2.5",
  "الذيل الأيمن (أكبر قيمة − Q₃):\\n13 − 12 = 1",
  "الذيل الأيسر (Q₁ − أصغر قيمة):\\n7 − 3 = 4",
  "الفضاء (عدد طرق اختيار ٣ من ١٥):\\n15C3 = 455",
  "صحيح — 13P4 = 715 × 4! = 17160",
];
FIXED.forEach(function(s){
  ok(src.indexOf(s)>=0,'موجود: «'+s.replace(/\\n/g,' ⏎ ').slice(0,52)+'»');
});

console.log('\n٣) القاعدة الشكلية: معادلةٌ بذيلٍ رقميٍّ صرفٍ بعد رمزٍ لاتيني في سطرٍ عربي');
// لا تُفشِل البناء (ليست كل حالةٍ منقلبة — أُثبت ذلك بالصورة)، لكنها تُعرَض للفحص البصري
// عند إضافة محتوًى جديد. **تنبيهٌ يُنظَر إليه، لا حكمٌ يُصدَر** — وهذا هو الفرق الذي
// جعل الكاشف الأوّل عديم القيمة.
const AR=/[ء-غف-ي]/,LAT=/[A-Za-z]/;
function risky(line){
  if(!AR.test(line)||!LAT.test(line))return false;
  const m=line.match(/[A-Za-z](?![\s\S]*[A-Za-z])/);
  if(!m)return false;
  const tail=line.slice(line.lastIndexOf(m[0])+1);
  if(LAT.test(tail)||AR.test(tail))return false;
  return (tail.match(/\d+(?:[.,٫]\d+)?/g)||[]).length>=2;
}
const hits=[];
src.split('\n').forEach(function(l,i){
  (l.match(/"((?:[^"\\]|\\.)*)"/g)||[]).forEach(function(q){
    q.slice(1,-1).replace(/\\n/g,'\n').split('\n').forEach(function(seg){
      seg=seg.trim();if(seg&&risky(seg))hits.push((i+1)+': '+seg.slice(0,70));
    });
  });
});
console.log('   أسطرٌ بهذا الشكل (للفحص البصري لا للإفشال): '+hits.length);
hits.slice(0,8).forEach(function(h){console.log('     • '+h)});
ok(true,'القاعدة تعمل — ونسبةُ بلاغها الكاذب معروفةٌ ومعلنة (٤ حقيقية من ١٤ مصوَّرة)');

console.log(fails?`\n=== ${fails} فشل ===`:'\n=== كل الاختبارات نجحت ===');
process.exit(fails?1:0);
