function parse(src,name){
  const out=[],errs=[];
  src.split("\n").forEach(function(ln,li){
    const t=ln.trim();if(!t)return;
    const p=t.split("|");
    if(p.length!==6){errs.push(name+" سطر "+(li+1)+": حقولٌ "+p.length+" لا ٦");return}
    out.push({q:p[0].trim(),key:p[1].trim(),d:[p[2].trim(),p[3].trim(),p[4].trim()],w:p[5].trim(),line:li+1});
  });
  return{items:out,errs:errs};
}

